auto aqueousSpecies(Database const& db) -> SpeciesList
{
    SpeciesList list;
    for(auto const& name : names)
        list.append(db.species().get(name));
    return list;
}

auto lngamma(ActivityModel const& fn, Index N, double T, double P, std::vector<double> const& n) -> ArrayXd
{
    ArrayXr x(N);
    double sum = 0.0;
    for(auto i = 0; i < N; ++i) sum += n[i];
    for(auto i = 0; i < N; ++i) x[i] = n[i]/sum;
    ActivityProps props = ActivityProps::create(N);
    fn(props, {T, P, x});
    ArrayXd out(N);
    for(auto i = 0; i < N; ++i) out[i] = props.ln_g[i].val();
    return out;
}

